export type MessageKey = keyof (typeof messages)["en"];

export const LOCALE_COOKIE = "kentron-locale";
export const LANGUAGE_STORAGE_KEY = "kentron-language";

export function resolveLocale(preference: LanguagePreference): Locale {
  if (preference === "en" || preference === "hy") return preference;
  if (typeof navigator !== "undefined" && navigator.language.startsWith("hy")) {
    return "hy";
  }
  return "en";
}

export function t(locale: Locale, key: MessageKey) {
  return messages[locale][key];
}

